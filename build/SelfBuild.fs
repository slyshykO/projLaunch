module SelfBuild

open System
open System.Collections.Generic
open System.IO
open System.Xml.Linq

module private Internal =
    let projectFilePath = Path.Combine(__SOURCE_DIRECTORY__, "build.fsproj")
    let hashesFilePath = Path.Combine(__SOURCE_DIRECTORY__, "obj", "hashes.fs")

    let directoryOfFile (path: string) =
        match Path.GetDirectoryName path with
        | null -> invalidArg (nameof path) $"File has no parent directory: {path}"
        | directory -> directory

    let buildInputs (projectFilePath: string) =
        let projectFilePath = Path.GetFullPath projectFilePath
        let projectDir = directoryOfFile projectFilePath
        let generatedHashes = Path.Combine(projectDir, "obj", "hashes.fs")
        let inputs = HashSet<string>(StringComparer.OrdinalIgnoreCase)
        let projects = HashSet<string>(StringComparer.OrdinalIgnoreCase)

        let addExisting path =
            if File.Exists path then
                inputs.Add(Path.GetFullPath path) |> ignore

        let rec addSharedConfiguration (directory: DirectoryInfo) =
            for name in
                [ "Directory.Build.props"
                  "Directory.Build.targets"
                  "Directory.Packages.props"
                  "global.json"
                  "NuGet.Config"
                  "nuget.config" ] do
                addExisting (Path.Combine(directory.FullName, name))

            match directory.Parent with
            | null -> ()
            | parent -> addSharedConfiguration parent

        let rec visitProject path =
            let path = Path.GetFullPath path

            if projects.Add path then
                inputs.Add path |> ignore
                let directory = directoryOfFile path
                addSharedConfiguration (DirectoryInfo directory)
                addExisting (Path.Combine(directory, "packages.lock.json"))

                // Like the reference helper, these projects use explicit item paths.
                // Read XML rather than launching MSBuild on every invocation.
                let project = XDocument.Load path

                let includes name =
                    project.Descendants()
                    |> Seq.filter (fun element -> element.Name.LocalName = name)
                    |> Seq.choose (fun element ->
                        match element.Attribute(XName.Get "Include") with
                        | null -> None
                        | attribute -> Some(Path.GetFullPath(Path.Combine(directory, attribute.Value))))

                for source in includes "Compile" do
                    if not (StringComparer.OrdinalIgnoreCase.Equals(source, generatedHashes)) then
                        inputs.Add source |> ignore

                for reference in includes "ProjectReference" do
                    visitProject reference

        visitProject projectFilePath
        addExisting (Path.Combine(projectDir, "scripts", "genhashes.fsx"))
        addExisting (Path.Combine(projectDir, "..", "build.bat"))
        inputs |> Seq.sort |> Seq.toList

let private fileHash (filePath: string) =
    use stream = File.OpenRead filePath
    use sha256 = Security.Cryptography.SHA256.Create()
    let hashBytes = sha256.ComputeHash stream
    Convert.ToHexString(hashBytes).ToLowerInvariant()

let hashStringsForProject projectFilePath =
    Internal.buildInputs projectFilePath
    |> List.map (fun filePath -> $"{filePath}|{fileHash filePath}")

let private hashStrings () =
    hashStringsForProject Internal.projectFilePath

let saveHashesToFile () =
    Directory.CreateDirectory(Internal.directoryOfFile Internal.hashesFilePath)
    |> ignore

    let fileBuilder = Text.StringBuilder()

    fileBuilder.AppendLine "// This file is auto-generated by SelfBuild.fs. Do not edit manually."
    |> ignore

    fileBuilder.AppendLine "module SelfBuildHashes" |> ignore
    fileBuilder.AppendLine() |> ignore
    fileBuilder.AppendLine "let hashes = [" |> ignore

    hashStrings ()
    |> List.iter (fun line ->
        let escapedLine = line.Replace("\\", "\\\\").Replace("\"", "\\\"")
        fileBuilder.AppendLine $"    \"{escapedLine}\"" |> ignore)

    fileBuilder.AppendLine "]" |> ignore
    File.WriteAllText(Internal.hashesFilePath, fileBuilder.ToString())

type SelfCheckResult =
    | AllGood
    | NeedToRebuild

#if !INTERACTIVE

let selfCheck () =
    try
        // Use the snapshot embedded in this executable, not the generated file on disk.
        if hashStrings () = SelfBuildHashes.hashes then
            AllGood
        else
            Console.WriteLine "Self-check failed: hashes do not match"
            NeedToRebuild
    with ex ->
        Console.WriteLine $"Self-check failed: {ex.Message}"
        NeedToRebuild

#endif
